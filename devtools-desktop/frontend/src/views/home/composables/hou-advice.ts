const SPRING_TERMS = new Set(['立春', '雨水', '惊蛰', '春分', '清明', '谷雨'])
const SUMMER_TERMS = new Set(['立夏', '小满', '芒种', '夏至', '小暑', '大暑'])
const AUTUMN_TERMS = new Set(['立秋', '处暑', '白露', '秋分', '寒露', '霜降'])

const STEP = 17

export function seasonFromTerm(termName: string): SeasonName {
  if (SPRING_TERMS.has(termName)) return '春'
  if (SUMMER_TERMS.has(termName)) return '夏'
  if (AUTUMN_TERMS.has(termName)) return '秋'
  return '冬'
}

export function poolForSeason(season: SeasonName) {
  return [...SEASON_TIPS[season], ...COMMON_TIPS]
}

function unixDay(dateKey: string) {
  const [year, month, day] = dateKey.split('-').map(Number)
  return Math.floor(Date.UTC(year, month - 1, day) / 86_400_000)
}

function termSalt(termName: string) {
  let value = 0
  for (const char of termName) value += char.charCodeAt(0)
  return value
}

export function adviceForDay(dateKey: string, termName: string, festival: string | null) {
  if (festival && FESTIVAL_ADVICE[festival]) return FESTIVAL_ADVICE[festival]
  const pool = poolForSeason(seasonFromTerm(termName))
  const index = Math.abs(unixDay(dateKey) * STEP + termSalt(termName)) % pool.length
  return pool[index] ?? '把步子放慢。今天够了，就很好。'
}
